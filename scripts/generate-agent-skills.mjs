import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const skillRoot = realpathSync(path.join(root, "skills"));
const require = createRequire(path.join(root, "packages/adapters/package.json"));
const rootRequire = createRequire(path.join(root, "package.json"));
const { parse } = require("yaml");
const manifest = JSON.parse(readFileSync(path.join(skillRoot, "manifest.json"), "utf8"));
const hash = (text) => createHash("sha256").update(text).digest("hex");
function read(relative) {
  const target = realpathSync(path.resolve(skillRoot, relative));
  if (!target.startsWith(`${skillRoot}${path.sep}`)) throw new Error("Skill path escapes bundle");
  return readFileSync(target, "utf8").replaceAll("\r\n", "\n");
}
const seen = new Set();
const skills = manifest.skills.map((entry) => {
  const content = read(`${entry.path}/SKILL.md`);
  const header = /^---\n([\s\S]*?)\n---(?:\n|$)/.exec(content);
  if (!header) throw new Error(`Missing skill frontmatter: ${entry.path}`);
  const { name, description } = parse(header[1]);
  if (typeof name !== "string" || !name || typeof description !== "string" || !description)
    throw new Error(`Invalid skill metadata: ${entry.path}`);
  if (seen.has(name)) throw new Error(`Duplicate skill: ${name}`);
  seen.add(name);
  const resources = {};
  for (const resource of entry.resources) {
    if (
      resource.includes("\\") ||
      resource.split("/").some((part) => !part || part === "." || part === "..") ||
      !/^[a-zA-Z0-9_./-]+$/.test(resource)
    )
      throw new Error(`Invalid skill resource: ${entry.path}`);
    const body = read(`${entry.path}/${resource}`);
    resources[resource] = { content: body, sha256: hash(body) };
  }
  return {
    name,
    description,
    content,
    resources,
    version: hash(JSON.stringify({ content, resources })),
  };
});
const serialized = `// Generated by scripts/generate-agent-skills.mjs; edit skills/ sources.\n// Adapted skill licenses and source notices: THIRD_PARTY_NOTICES.md.\nexport interface ProductSkill {\n  name: string;\n  description: string;\n  content: string;\n  version: string;\n  resources: Record<string, { content: string; sha256: string }>;\n}\n\nexport const PRODUCT_SKILLS: readonly ProductSkill[] = ${JSON.stringify(skills, null, 2)};\n`;
const destination = path.join(root, "packages/adapters/src/product-skills.generated.ts");
const biomePackage = rootRequire.resolve("@biomejs/biome/package.json");
const biome = path.resolve(
  path.dirname(biomePackage),
  JSON.parse(readFileSync(biomePackage, "utf8")).bin.biome,
);
const output = execFileSync(
  process.execPath,
  [biome, "format", `--stdin-file-path=${destination}`],
  {
    cwd: root,
    input: serialized,
    encoding: "utf8",
  },
);
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8").replaceAll("\r\n", "\n") !== output)
    throw new Error("Product skill catalog is stale. Run pnpm skills:generate.");
} else writeFileSync(destination, output);
process.stdout.write(`Verified ${skills.length} product skills.\n`);
